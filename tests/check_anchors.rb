#!/usr/bin/env ruby
# frozen_string_literal: true

# Anchor/link consistency checker.
#
# FORMAT
#   definition :  [anchor:<id>-<label>]      e.g. [anchor:NNN-Implicit-Delegation]
#   reference  :  [link:<id>-<label>]        e.g. [link:NNN-Implicit-Delegation]
#
# Only <id> (the digits) is matched. <label> is freeform human text and may be
# edited at will; renaming a label never breaks a link. That split is what lets
# content anchors survive edits, unlike the row:N scheme this replaced.
#
# CHECKS
#   1. every anchor id is defined exactly once, repo-wide
#   2. every link id resolves to a defined anchor
#   3. no row:N reference remains
#   4. no line exceeds MAX_WIDTH columns
#   5. .anchors.json holds only next_anchor_id, and it stays ahead of every id
#      in use so a retired number is never handed out twice
#
# Usage: ruby tests/check_anchors.rb [--list]

require "json"
require "pathname"

MAX_WIDTH = 120
ROOT = Pathname.new(__dir__).parent
REGISTRY = ROOT.join(".anchors.json")

DEF_RE = /\[anchor:(\d+)-([^\]\s]*)\]/.freeze
LINK_RE = /\[link:(\d+)-([^\]\s]*)\]/.freeze
ROW_RE = /\brow:\d+/.freeze

# all_samples.l is generated by concatenation; its markers are copies.
SKIP_GEN = "all_samples.l"

SCAN_GLOBS = %w[
  .cursor/rules/*.mdc
  examples/**/*.l
  tests/cases/**/*.l
  stdlib/**/*.l
  compiler/**/*.cpp
  compiler/**/*.hpp
  runtime/*.c
  CMakeLists.txt
  runtime/CMakeLists.txt
  tests/*.rb
].freeze

def rel_of(path)
  Pathname.new(path).relative_path_from(ROOT).to_s.tr("\\", "/")
end

def comment_body(rel, line)
  case rel
  when /\.(cpp|hpp|c)$/ then line[%r{//(.*)$}, 1]
  when /\.l$/ then line[%r{//(.*)$}, 1]
  when /\.md$/, /\.mdc$/ then line[%r{<!--(.*?)-->}, 1]
  when /\.rb$/, %r{(^|/)CMakeLists\.txt$} then line[/#(.*)$/, 1]
  end
end

errors = []
defs = Hash.new { |h, k| h[k] = [] }
links = []

files = SCAN_GLOBS.flat_map { |g| Dir.glob(ROOT.join(g)) }.uniq.sort
files.each do |file|
  rel = rel_of(file)
  next if File.basename(file) == SKIP_GEN
  File.read(file, encoding: "UTF-8").lines.each_with_index do |line, i|
    body = comment_body(rel, line)
    next if body.nil?
    where = "#{rel}:#{i + 1}"

    # .mdc rules carry their anchors as <!-- anchor:N-Label -->. Rewrite that to
    # the bracket form so one regex pair covers every file type.
    scope =
      if rel.end_with?(".mdc")
        line.gsub(/<!--\s*(anchor|link):(\d+)-([^\s>]*)\s*-->/) do
          kind = Regexp.last_match(1)
          num = Regexp.last_match(2)
          label = Regexp.last_match(3)
          "[#{kind}:#{num}-#{label}]"
        end
      else
        body
      end

    # Any [anchor:..] in a comment defines that id; any [link:..] refers to one.
    scope.scan(DEF_RE) do |(id, label)|
      defs[id] << { where: where, label: label }
    end
    scope.scan(LINK_RE) do |(id, label)|
      links << { id: id, label: label, where: where }
    end

    if line =~ ROW_RE
      errors << "#{where}: row:N reference still present (#{line.strip[0, 60]})"
    end
    # Width applies to real comments only. If the `//` sits inside a string
    # literal (odd number of quotes before it) it is not a comment; skip.
    cpos = line.index("//")
    in_string = cpos && line[0...cpos].count('"').odd?
    check_width = !rel.end_with?(".mdc") && !in_string
    if check_width
      n = line.chomp.length
      errors << "#{where}: #{n} columns (max #{MAX_WIDTH})" if n > MAX_WIDTH
    end
  end
end

# 1. Unique definitions.
defs.each do |id, list|
  next if list.length == 1
  places = list.map { |d| d[:where] }.join(", ")
  errors << "anchor #{id} defined #{list.length}x: #{places}"
end

# 2. Dangling links.
links.each do |l|
  next if defs.key?(l[:id])
  errors << "#{l[:where]}: link #{l[:id]} has no anchor definition"
end

# 3. Counter agreement: .anchors.json holds ONLY the next id to hand out, so a
#    retired number is never reissued. The definitions on disk are the authority
#    for what exists; the counter only has to stay ahead of them.
if REGISTRY.exist?
  reg = JSON.parse(REGISTRY.read(encoding: "UTF-8"))
  nxt = reg["next_anchor_id"].to_i
  max_id = defs.keys.map(&:to_i).max || 0
  if nxt.zero?
    errors << ".anchors.json has no numeric next_anchor_id"
  elsif nxt <= max_id
    errors << ".anchors.json next_anchor_id=#{nxt} does not exceed the highest " \
              "id in use (#{max_id}); a new anchor would collide"
  end
else
  puts "note: .anchors.json absent, skipping counter check"
end

if ARGV.include?("--list")
  defs.keys.sort_by(&:to_i).each do |id|
    puts format("%-5s %-38s %s", id, defs[id].first[:label], defs[id].first[:where])
  end
  puts
  puts "#{defs.size} anchors, #{links.size} links"
  exit(errors.empty? ? 0 : 1)
end

if errors.empty?
  puts "OK: #{defs.size} anchors, #{links.size} links resolve, " \
       "no row:N, all lines <= #{MAX_WIDTH}"
  exit 0
end

warn "FAIL: #{errors.size} anchor/link problem(s)"
errors.each { |e| warn "  - #{e}" }
exit 1
