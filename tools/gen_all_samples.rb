#!/usr/bin/env ruby
# frozen_string_literal: true

# Builds examples/all_samples.l: every examples/*.l and tests/cases/**/*.l
# concatenated under a `// <rel-path>` banner, preceded by a generated table of
# contents.
#
# The TOC uses explicit `row:N` links. Rows must account for the TOC's own
# height, so generation is TWO-PASS and never does offset arithmetic:
#   1. write the file with a placeholder TOC of the final height,
#   2. read the file back, find each banner's real row,
#   3. write again with those rows baked into the same-size TOC.

root = File.expand_path("..", __dir__)
out = File.join(root, "examples", "all_samples.l")

# Samples that are EXPECTED to fail compilation (negative tests). They are kept
# at the end of the file, behind a banner, so the reference section above stays
# readable and is not polluted by deliberately invalid code.
NEGATIVE = /(?:_bad|_fail|sync_fail)\z/.freeze

good = []
bad = []
Dir.glob(File.join(root, "examples", "*.l")).sort.each do |f|
  next if File.basename(f).include?("all_samples")
  (File.basename(f, ".l") =~ NEGATIVE ? bad : good) << f
end
Dir.glob(File.join(root, "tests", "cases", "**", "*.l")).sort.each do |f|
  next if File.basename(f).start_with?("_tmp")
  (File.basename(f, ".l") =~ NEGATIVE ? bad : good) << f
end

def rel_path(root, f)
  f.sub("#{root}/", "").sub("#{root}\\", "").tr("\\", "/")
end

def banner(rel)
  "//------------------------------------------------\n// #{rel}\n//------------------------------------------------\n"
end

def slice(root, files)
  files.map do |f|
    rel = rel_path(root, f)
    body = File.read(f, encoding: "UTF-8")
    body = body.sub(/\A\uFEFF/, "").rstrip + "\n"
    [banner(rel) + body, rel]
  end
end

good_parts = slice(root, good)
bad_parts = slice(root, bad)

negative_header = bad.empty? ? "" : <<~TXT
  //================================================
  // NEGATIVE SAMPLES — these MUST FAIL to compile.
  // Listed for reference only; do not copy their syntax.
  //================================================
TXT

parts = good_parts + bad_parts
header = "// 本文件由 tools/gen_all_samples.rb 生成，包含 #{parts.length} 个例子。\n\n"
body_text = good_parts.map(&:first).join("\n") +
            (bad_parts.empty? ? "" : "\n" + negative_header) +
            bad_parts.map(&:first).join("\n")
rels = parts.map(&:last)

# TOC frame: 3 boilerplate lines, one line per sample, then a blank trailer.
TOC_FRAME = 3
TOC_TRAILER = 1
toc_height = TOC_FRAME + rels.length + TOC_TRAILER

def render_toc(rels, rows)
  lines = []
  lines << "// Contents — row:N is the line of that sample's banner in THIS file."
  lines << "// Generated by tools/gen_all_samples.rb; do not edit by hand."
  lines << "//"
  rels.each do |rel|
    row = rows[rel]
    lines << if row
               format("//   %-46s row:%d", rel, row)
             else
               format("//   %-46s row:?", rel)
             end
  end
  lines << "" # blank separator before the body
  lines
end

# Pass 1: placeholder TOC of the exact final height.
placeholder = render_toc(rels, {})
raise "TOC height mismatch (#{placeholder.length} != #{toc_height})" unless placeholder.length == toc_height

# --check renders into a scratch file and compares; the real file is untouched.
CHECK = ARGV.include?("--check")
scratch = CHECK ? out.sub(/\.l\z/, ".check.l") : out
File.write(scratch, header + placeholder.join("\n") + "\n" + body_text, encoding: "UTF-8")

# Pass 2: read real banner rows from the file we just wrote.
rows = {}
File.readlines(scratch, encoding: "UTF-8").each_with_index do |line, i|
  if line =~ %r{^// (examples/.+\.l|tests/.+\.l)$}
    rows[Regexp.last_match(1)] = i + 1
  end
end
missing = rels.reject { |r| rows.key?(r) }
raise "banners not found in output: #{missing.first(3).inspect}" unless missing.empty?

final = render_toc(rels, rows)
raise "TOC grew on pass 2" unless final.length == placeholder.length
rendered = header + final.join("\n") + "\n" + body_text

if CHECK
  File.delete(scratch)
  if File.exist?(out) && File.read(out, encoding: "UTF-8") == rendered
    puts "OK: #{File.basename(out)} is up to date (#{parts.length} samples)"
    exit 0
  end
  warn "STALE: #{File.basename(out)} does not match its sources"
  warn "       fix with: ruby tools/gen_all_samples.rb"
  exit 1
end

File.write(out, rendered, encoding: "UTF-8")

puts "wrote #{out}"
puts "  #{parts.length} samples (#{good_parts.length} ok, #{bad_parts.length} negative), #{File.size(out)} bytes, TOC #{toc_height} rows"
